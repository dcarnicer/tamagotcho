#pragma once
// Unicode -> CP437 glyph index for the built-in GLCD font (Font0). Font0 keeps
// Latin-1 letters in its CP437 slots, not at their Unicode positions, so
// accented text has to be translated before drawing. Pure C++ (native-tested).
#include <cstdint>

namespace tgc {

// CP437 index to draw with Font0 for `cp`, or -1 if the font has no glyph.
inline int glcdIndex(uint32_t cp) {
    if (cp >= 0x20 && cp <= 0x7E) return static_cast<int>(cp);
    struct M {
        uint32_t cp;
        uint8_t idx;
    };
    static constexpr M kMap[] = {
        {0x00C7, 0x80}, {0x00FC, 0x81}, {0x00E9, 0x82}, {0x00E2, 0x83}, {0x00E4, 0x84},
        {0x00E0, 0x85}, {0x00E5, 0x86}, {0x00E7, 0x87}, {0x00EA, 0x88}, {0x00EB, 0x89},
        {0x00E8, 0x8A}, {0x00EF, 0x8B}, {0x00EE, 0x8C}, {0x00EC, 0x8D}, {0x00C4, 0x8E},
        {0x00C5, 0x8F}, {0x00C9, 0x90}, {0x00E6, 0x91}, {0x00C6, 0x92}, {0x00F4, 0x93},
        {0x00F6, 0x94}, {0x00F2, 0x95}, {0x00FB, 0x96}, {0x00F9, 0x97}, {0x00FF, 0x98},
        {0x00D6, 0x99}, {0x00DC, 0x9A}, {0x00F8, 0x9B}, {0x00A3, 0x9C}, {0x00D8, 0x9D},
        {0x00D7, 0x9E}, {0x0192, 0x9F}, {0x00E1, 0xA0}, {0x00ED, 0xA1}, {0x00F3, 0xA2},
        {0x00FA, 0xA3}, {0x00F1, 0xA4}, {0x00D1, 0xA5}, {0x00AA, 0xA6}, {0x00BA, 0xA7},
        {0x00BF, 0xA8}, {0x00AC, 0xAA}, {0x00BD, 0xAB}, {0x00BC, 0xAC}, {0x00A1, 0xAD},
        {0x00AB, 0xAE}, {0x00BB, 0xAF},
        // Separators: U+00B7 '·' as CP437's 2x2 dot 0xF9 (it reads better at 1x
        // than 0xFA's 2x1 dot), U+2022 '•' as 0x07, U+00B0 '°' as 0xF8.
        {0x00B7, 0xF9}, {0x2022, 0x07}, {0x00B0, 0xF8},
    };
    for (const M& m : kMap)
        if (m.cp == cp) return m.idx;
    return -1;
}

}  // namespace tgc
