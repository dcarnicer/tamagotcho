"""Regenerate the tiny deterministic firmware test fixture (mini.tgc + mini.json)."""

from __future__ import annotations

import json
from pathlib import Path

from . import paths
from .build import build_pack
from .kanjidic import make_cards, parse_kanjidic
from .pack import read_pack

MINI_XML = Path(__file__).resolve().parents[2] / "tests" / "data" / "mini_kanjidic2.xml"
MINI_JLPT = {0x65E5: 5, 0x6708: 5, 0x706B: 5}
SIZES = dict(large_px=32, small_px=16, text_px=12, option_px=18)


def build_mini(font_path: Path) -> bytes:
    cards = make_cards(parse_kanjidic(MINI_XML.read_bytes()), "en", {5}, None, MINI_JLPT)
    return build_pack(cards, font_path, "en", "JLPT N5", build_time=0, **SIZES)


def expected_json(raw: bytes) -> dict:
    p = read_pack(raw)
    assert not p.errors, p.errors
    h = p.header
    return {
        "_comment": "Expected decoded fields of mini.tgc. All offsets are absolute file offsets "
                    "(including string and distractor offsets in cards). Generated by "
                    "`tangocho-pack fixture`.",
        "file_size": len(raw),
        "header": {k: h[k] for k in (
            "version", "header_size", "card_count", "glyph_count", "cards_off", "glyphs_off",
            "distract_off", "strings_off", "strings_size", "glyph_data_off", "deck_name",
            "lang", "large_px", "small_px", "text_px", "text_line_height", "text_ascent",
            "option_px", "option_line_height", "option_ascent", "build_time")},
        "deck_name": p.deck_name,
        "cards": [{
            "codepoint": c.codepoint, "char": chr(c.codepoint), "meanings": c.meanings,
            "onyomi": c.onyomi, "kunyomi": c.kunyomi, "string_offsets": list(c.string_offs),
            "distractor_off": c.distractor_off, "distractors": c.distractors,
            "distractor_read_off": c.distractor_read_off, "distractors_reading": c.distractors_reading,
            "jlpt": c.jlpt, "grade": c.grade, "strokes": c.strokes, "flags": c.flags,
            "freq": c.freq, "level": c.level,
        } for c in p.cards],
        "glyph_table_first": [g.__dict__ for g in p.glyphs[:3]],
        "glyph_table_samples": [
            {**g.__dict__, "bitmap_hex": p.raw[g.data_off:g.data_off + ((g.width + 1) // 2) * g.height].hex()}
            for g in (p.find_glyph(0, 0x65E5), p.find_glyph(1, 0x65E5), p.find_glyph(2, ord("A")),
                      p.find_glyph(2, ord(" ")), p.find_glyph(2, 0x30CB))
            if g is not None
        ],
        "glyph_counts_per_set": {str(s): sum(1 for g in p.glyphs if g.set == s) for s in (0, 1, 2, 3)},
    }


def write_fixture(font_path: Path | None = None, out_dir: Path | None = None) -> tuple[Path, Path]:
    font_path = font_path or paths.DEFAULT_FONT
    out_dir = out_dir or paths.FIXTURES
    out_dir.mkdir(parents=True, exist_ok=True)
    raw = build_mini(font_path)
    tgc, js = out_dir / "mini.tgc", out_dir / "mini.json"
    tgc.write_bytes(raw)
    js.write_text(json.dumps(expected_json(raw), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return tgc, js
