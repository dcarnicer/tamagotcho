GLYPH_W, GLYPH_H, GLYPH_ASCENT = 6, 8, 7


def glcd_index(cp: int) -> int:
    """CP437 glyph index for `cp`, or -1 if the font has no glyph."""
    if 0x20 <= cp <= 0x7E:
        return cp
    return _CP437.get(cp, -1)


def can_draw(s: str) -> bool:
    return all(glcd_index(ord(ch)) >= 0 for ch in s)


def glyph_columns(index: int) -> bytes:
    return _FONT[index * 5 : index * 5 + 5]
